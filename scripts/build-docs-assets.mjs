import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const root = process.cwd();
const require = createRequire(import.meta.url);
const componentModuleFile = fileURLToPath(import.meta.resolve("#design-system/components"));
const componentModuleOutputDir = path.join(root, "apps/docs/generated/components");
const legacyComponentModuleOutputDir = path.join(root, "apps/docs/generated/components");
const componentSourceFile = fileURLToPath(import.meta.resolve("#design-system/components-css"));
const componentOutputFile = path.join(root, "apps/docs/generated/components.css");
const legacyComponentOutputFile = path.join(root, "apps/docs/generated/components.css");
const tokenSourceFile = fileURLToPath(import.meta.resolve("#design-system/tokens-css"));
const tokenOutputFile = path.join(root, "apps/docs/generated/tokens.css");
const legacyTokenOutputFile = path.join(root, "apps/docs/generated/tokens.css");
const vendorOutputDir = path.join(root, "apps/docs/generated/vendor");
const reactOutputDir = path.join(root, "apps/docs/generated/react");

function generatedHeader(source) {
  return [
    "/* Generated by scripts/build-docs-assets.mjs.",
    `   Source: ${source}`,
    "   Do not edit this file by hand. */",
    "",
  ].join("\n");
}

function firstExistingPath(paths) {
  for (const candidate of paths) {
    if (fs.existsSync(candidate)) return candidate;
  }
  return "";
}

function dependencyFile(packageName, relativePath) {
  const directPackage = path.join(root, "node_modules", packageName, relativePath);
  const flowPackage = path.join(root, "node_modules/flow/node_modules", packageName, relativePath);
  const resolvedPackage = (() => {
    try {
      return path.join(path.dirname(require.resolve(`${packageName}/package.json`)), relativePath);
    } catch {
      return "";
    }
  })();
  const file = firstExistingPath([directPackage, flowPackage, resolvedPackage]);
  if (!file) throw new Error(`Unable to locate ${packageName}/${relativePath} for docs assets.`);
  return file;
}

const tokenSource = fs.readFileSync(tokenSourceFile, "utf8");
const componentSource = fs.readFileSync(componentSourceFile, "utf8").replace(
  /@import "\.\.\/\.\.\/tokens\/styles\/tokens\.css\?v=\d+";/,
  '@import "./tokens.css?v=1";'
);

fs.mkdirSync(path.dirname(componentOutputFile), { recursive: true });
fs.rmSync(legacyComponentModuleOutputDir, { recursive: true, force: true });
fs.rmSync(legacyComponentOutputFile, { force: true });
fs.rmSync(legacyTokenOutputFile, { force: true });
fs.rmSync(componentModuleOutputDir, { recursive: true, force: true });
fs.rmSync(reactOutputDir, { recursive: true, force: true });
fs.cpSync(path.dirname(componentModuleFile), componentModuleOutputDir, { recursive: true });
const reactDistSource = firstExistingPath([
  path.join(root, "packages/react/dist"),
  path.join(root, "node_modules/flow/packages/react/dist"),
]);
if (!reactDistSource) throw new Error("Unable to locate @design-system/react dist for docs assets.");
fs.cpSync(reactDistSource, reactOutputDir, { recursive: true });
for (const file of fs.readdirSync(reactOutputDir).filter((name) => name.endsWith(".js") || name.endsWith(".d.ts"))) {
  const outputFile = path.join(reactOutputDir, file);
  const extensionSuffix = file.endsWith(".js") ? "?v=1" : "";
  fs.writeFileSync(
    outputFile,
    fs.readFileSync(outputFile, "utf8")
      .replaceAll('"@design-system/components/platforms"', `"../components/platforms/index.js${extensionSuffix}"`)
      .replaceAll('"@alohasoyrico-eng/flow/components/platforms"', `"../components/platforms/index.js${extensionSuffix}"`)
      .replaceAll('"#flow/platforms"', `"../components/platforms/index.js${extensionSuffix}"`)
      .replaceAll('"../../components/src/platforms/index.js"', `"../components/platforms/index.js${extensionSuffix}"`)
      .replaceAll('"@design-system/components"', `"../components/index.js${extensionSuffix}"`)
      .replaceAll('"@alohasoyrico-eng/flow/components"', `"../components/index.js${extensionSuffix}"`)
      .replaceAll('"#flow/components"', `"../components/index.js${extensionSuffix}"`)
      .replaceAll('"../../components/src/index.js"', `"../components/index.js${extensionSuffix}"`)
  );
}
fs.writeFileSync(tokenOutputFile, `${generatedHeader("packages/tokens/styles/tokens.css")}${tokenSource}`);
fs.writeFileSync(componentOutputFile, `${generatedHeader("packages/components/styles/components.css")}${componentSource}`);
fs.mkdirSync(vendorOutputDir, { recursive: true });
fs.copyFileSync(dependencyFile("react", "umd/react.production.min.js"), path.join(vendorOutputDir, "react.production.min.js"));
fs.copyFileSync(dependencyFile("react-dom", "umd/react-dom.production.min.js"), path.join(vendorOutputDir, "react-dom.production.min.js"));
fs.writeFileSync(
  path.join(vendorOutputDir, "react.esm.js"),
  `${generatedHeader("react/umd/react.production.min.js")}const React = globalThis.React;\nexport default React;\nexport const Children = React.Children;\nexport const Component = React.Component;\nexport const Fragment = React.Fragment;\nexport const StrictMode = React.StrictMode;\nexport const Suspense = React.Suspense;\nexport const cloneElement = React.cloneElement;\nexport const createContext = React.createContext;\nexport const createElement = React.createElement;\nexport const createFactory = React.createFactory;\nexport const createRef = React.createRef;\nexport const forwardRef = React.forwardRef;\nexport const isValidElement = React.isValidElement;\nexport const lazy = React.lazy;\nexport const memo = React.memo;\nexport const startTransition = React.startTransition;\nexport const useCallback = React.useCallback;\nexport const useContext = React.useContext;\nexport const useDebugValue = React.useDebugValue;\nexport const useDeferredValue = React.useDeferredValue;\nexport const useEffect = React.useEffect;\nexport const useId = React.useId;\nexport const useImperativeHandle = React.useImperativeHandle;\nexport const useInsertionEffect = React.useInsertionEffect;\nexport const useLayoutEffect = React.useLayoutEffect;\nexport const useMemo = React.useMemo;\nexport const useReducer = React.useReducer;\nexport const useRef = React.useRef;\nexport const useState = React.useState;\nexport const useSyncExternalStore = React.useSyncExternalStore;\nexport const useTransition = React.useTransition;\nexport const version = React.version;\n`
);
fs.writeFileSync(
  path.join(vendorOutputDir, "react-dom-client.esm.js"),
  `${generatedHeader("react-dom/umd/react-dom.production.min.js")}const ReactDOM = globalThis.ReactDOM;\nexport const createRoot = ReactDOM.createRoot;\nexport const hydrateRoot = ReactDOM.hydrateRoot;\n`
);
let echartsSourceFile = "";
for (const candidate of ["echarts/dist/echarts.esm.min.js", path.join(root, "apps/docs/vendor/echarts.esm.min.js")]) {
  try {
    echartsSourceFile = candidate.startsWith("/") ? candidate : require.resolve(candidate);
    if (fs.existsSync(echartsSourceFile)) break;
  } catch {
    echartsSourceFile = "";
  }
}
if (echartsSourceFile && fs.existsSync(echartsSourceFile)) {
  fs.copyFileSync(echartsSourceFile, path.join(vendorOutputDir, "echarts.esm.min.js"));
  console.log(`Built docs vendor bridge: ${path.relative(root, path.join(vendorOutputDir, "echarts.esm.min.js"))}`);
}
console.log(`Built docs asset bridge: ${path.relative(root, componentModuleOutputDir)}`);
console.log(`Built docs React bridge: ${path.relative(root, reactOutputDir)}`);
console.log(`Built docs asset bridge: ${path.relative(root, componentOutputFile)}`);
console.log(`Built docs asset bridge: ${path.relative(root, tokenOutputFile)}`);
